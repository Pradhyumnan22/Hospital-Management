CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    role VARCHAR(32) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medical_record_number VARCHAR(32) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    date_of_birth DATE NOT NULL,
    sex VARCHAR(16) NOT NULL,
    phone VARCHAR(32),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ward (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(16) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    ward_type VARCHAR(32) NOT NULL,
    floor_number INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE bed (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_id BIGINT NOT NULL REFERENCES ward (id),
    bed_code VARCHAR(16) NOT NULL,
    state VARCHAR(32) NOT NULL,
    isolation_capable BOOLEAN NOT NULL DEFAULT FALSE,
    has_ventilator BOOLEAN NOT NULL DEFAULT FALSE,
    has_monitor BOOLEAN NOT NULL DEFAULT FALSE,
    has_oxygen BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_bed_code_per_ward UNIQUE (ward_id, bed_code)
);

CREATE TABLE admission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patient (id),
    bed_id BIGINT NOT NULL REFERENCES bed (id),
    status VARCHAR(32) NOT NULL,
    diagnosis VARCHAR(255) NOT NULL,
    isolation_required BOOLEAN NOT NULL DEFAULT FALSE,
    required_ward_type VARCHAR(32),
    admitted_at TIMESTAMP NOT NULL,
    discharged_at TIMESTAMP,
    admitted_by VARCHAR(64) NOT NULL,
    discharged_by VARCHAR(64),
    discharge_notes VARCHAR(500),
    active_patient_key BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_one_active_admission UNIQUE (active_patient_key)
);

CREATE TABLE audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(64) NOT NULL,
    action VARCHAR(64) NOT NULL,
    entity_type VARCHAR(64) NOT NULL,
    entity_id VARCHAR(64),
    details VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    severity VARCHAR(16) NOT NULL,
    title VARCHAR(160) NOT NULL,
    message VARCHAR(500) NOT NULL,
    acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_bed_state ON bed (state);
CREATE INDEX idx_bed_ward ON bed (ward_id);
CREATE INDEX idx_admission_status ON admission (status);
CREATE INDEX idx_admission_admitted_at ON admission (admitted_at);
CREATE INDEX idx_admission_patient ON admission (patient_id);
CREATE INDEX idx_audit_created ON audit_event (created_at);
